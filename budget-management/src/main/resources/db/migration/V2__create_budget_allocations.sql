
-- ============================================
-- V2: Budget Allocation Management
-- ============================================

-- 1. Main Budget Allocation Table

CREATE TABLE budget_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    fiscal_year_id BIGINT NOT NULL,
    organization_id UUID NOT NULL,
    budget_type_id SMALLINT NOT NULL,
    budget_source_id SMALLINT NOT NULL,

    original_amount NUMERIC(18,2) NOT NULL,
    current_amount NUMERIC(18,2) NOT NULL,

    allocation_date DATE NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',

    remarks TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_allocation_fiscal_year
        FOREIGN KEY (fiscal_year_id)
        REFERENCES fiscal_years(id),

    CONSTRAINT fk_allocation_organization
        FOREIGN KEY (organization_id)
        REFERENCES organizations(id),

    CONSTRAINT fk_allocation_budget_type
        FOREIGN KEY (budget_type_id)
        REFERENCES budget_types(id),

    CONSTRAINT fk_allocation_budget_source
        FOREIGN KEY (budget_source_id)
        REFERENCES budget_sources(id),

    CONSTRAINT chk_allocation_original_amount
        CHECK (original_amount >= 0),

    CONSTRAINT chk_allocation_current_amount
        CHECK (current_amount >= 0),

    CONSTRAINT chk_allocation_status
        CHECK (status IN ('DRAFT', 'APPROVED')),

    CONSTRAINT uq_budget_allocation
        UNIQUE (
            fiscal_year_id,
            organization_id,
            budget_type_id,
            budget_source_id
        )
);


-- 2. Budget Allocation Revision History

CREATE TABLE budget_allocation_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    budget_allocation_id BIGINT NOT NULL,

    revision_no INTEGER NOT NULL,

    previous_amount NUMERIC(18,2) NOT NULL,
    revised_amount NUMERIC(18,2) NOT NULL,

    revision_reason TEXT NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',

    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    approved_at TIMESTAMPTZ,

    remarks TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_revision_allocation
        FOREIGN KEY (budget_allocation_id)
        REFERENCES budget_allocations(id),

    CONSTRAINT uq_allocation_revision_no
        UNIQUE (budget_allocation_id, revision_no),

    CONSTRAINT chk_revision_previous_amount
        CHECK (previous_amount >= 0),

    CONSTRAINT chk_revision_new_amount
        CHECK (revised_amount >= 0),

    CONSTRAINT chk_revision_status
        CHECK (
            status IN (
                'DRAFT',
                'SUBMITTED',
                'APPROVED',
                'REJECTED'
            )
        )
);


-- 3. Indexes

CREATE INDEX idx_allocation_fiscal_year
    ON budget_allocations(fiscal_year_id);

CREATE INDEX idx_allocation_organization
    ON budget_allocations(organization_id);

CREATE INDEX idx_allocation_budget_type
    ON budget_allocations(budget_type_id);

CREATE INDEX idx_revision_allocation
    ON budget_allocation_revisions(budget_allocation_id);

CREATE INDEX idx_revision_status
    ON budget_allocation_revisions(status);


-- Only one submitted revision per allocation at a time

CREATE UNIQUE INDEX uq_one_pending_revision_per_allocation
    ON budget_allocation_revisions(budget_allocation_id)
    WHERE status = 'SUBMITTED';
