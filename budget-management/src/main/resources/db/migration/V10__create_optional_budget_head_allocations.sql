CREATE TABLE budget_head_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_budget_allocation_id BIGINT REFERENCES office_budget_allocations(id) ON DELETE CASCADE,
    project_id BIGINT REFERENCES projects(id) ON DELETE CASCADE,
    expense_head_id BIGINT NOT NULL REFERENCES expense_heads(id),
    allocated_amount NUMERIC(20,2) NOT NULL CHECK (allocated_amount > 0),
    CONSTRAINT ck_budget_head_allocation_target CHECK (
        (office_budget_allocation_id IS NOT NULL AND project_id IS NULL) OR
        (office_budget_allocation_id IS NULL AND project_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_office_budget_head_allocation
    ON budget_head_allocations(office_budget_allocation_id, expense_head_id)
    WHERE office_budget_allocation_id IS NOT NULL;
CREATE UNIQUE INDEX uq_project_budget_head_allocation
    ON budget_head_allocations(project_id, expense_head_id)
    WHERE project_id IS NOT NULL;
