
-- =====================================================
-- V5: New Ministry Budget Management Structure
-- =====================================================

-- 1. Ministry's total government-approved budget
CREATE TABLE ministry_budgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fiscal_year_id BIGINT NOT NULL REFERENCES fiscal_years(id),
    organization_id UUID NOT NULL REFERENCES organizations(id),

    total_amount NUMERIC(20,2) NOT NULL,
    remarks TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_ministry_budget_year
        UNIQUE (fiscal_year_id, organization_id),

    CONSTRAINT ck_ministry_total_amount
        CHECK (total_amount >= 0)
);


-- 2. Three main budget categories
CREATE TABLE ministry_budget_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ministry_budget_id BIGINT NOT NULL
        REFERENCES ministry_budgets(id),

    category_code VARCHAR(30) NOT NULL,
    category_name VARCHAR(150) NOT NULL,
    total_amount NUMERIC(20,2) NOT NULL DEFAULT 0,

    remarks TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_ministry_budget_category
        UNIQUE (ministry_budget_id, category_code),

    CONSTRAINT ck_category_code
        CHECK (category_code IN (
            'OPERATIONAL',
            'SEDP',
            'DEVELOPMENT'
        )),

    CONSTRAINT ck_category_amount
        CHECK (total_amount >= 0)
);


-- 3. Optional ADP and BLOCK allocation under each category
CREATE TABLE category_budget_sources (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    category_id BIGINT NOT NULL
        REFERENCES ministry_budget_categories(id),

    source_code VARCHAR(20) NOT NULL,
    amount NUMERIC(20,2) NOT NULL DEFAULT 0,

    remarks TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_category_source
        UNIQUE (category_id, source_code),

    CONSTRAINT ck_category_source_code
        CHECK (source_code IN ('ADP', 'BLOCK')),

    CONSTRAINT ck_category_source_amount
        CHECK (amount >= 0)
);


-- 4. Office-wise budget allocation
CREATE TABLE office_budget_allocations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    category_source_id BIGINT NOT NULL
        REFERENCES category_budget_sources(id),

    organization_id UUID NOT NULL
        REFERENCES organizations(id),

    allocated_amount NUMERIC(20,2) NOT NULL,

    remarks TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_office_source_allocation
        UNIQUE (category_source_id, organization_id),

    CONSTRAINT ck_office_allocated_amount
        CHECK (allocated_amount >= 0)
);


-- 5. Projects under offices
CREATE TABLE projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    office_budget_allocation_id BIGINT NOT NULL
        REFERENCES office_budget_allocations(id),

    project_code VARCHAR(80) NOT NULL UNIQUE,
    project_name VARCHAR(300) NOT NULL,
    project_name_bn VARCHAR(300),

    allocated_amount NUMERIC(20,2) NOT NULL,

    start_date DATE,
    end_date DATE,

    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    remarks TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT ck_project_amount
        CHECK (allocated_amount >= 0),

    CONSTRAINT ck_project_status
        CHECK (status IN ('ACTIVE', 'COMPLETED', 'INACTIVE'))
);


-- 6. Project cumulative expenditure history
CREATE TABLE project_expenditure_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    project_id BIGINT NOT NULL REFERENCES projects(id),

    report_date DATE NOT NULL,
    cumulative_amount NUMERIC(20,2) NOT NULL,

    incremental_amount NUMERIC(20,2) NOT NULL DEFAULT 0,

    remarks TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_project_report_date
        UNIQUE (project_id, report_date),

    CONSTRAINT ck_project_cumulative_amount
        CHECK (cumulative_amount >= 0),

    CONSTRAINT ck_project_incremental_amount
        CHECK (incremental_amount >= 0)
);


-- 7. Office cumulative expenditure history
-- Used for Operational and Development Block expenditure
CREATE TABLE office_expenditure_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    office_budget_allocation_id BIGINT NOT NULL
        REFERENCES office_budget_allocations(id),

    report_date DATE NOT NULL,
    cumulative_amount NUMERIC(20,2) NOT NULL,

    incremental_amount NUMERIC(20,2) NOT NULL DEFAULT 0,

    remarks TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_office_report_date
        UNIQUE (office_budget_allocation_id, report_date),

    CONSTRAINT ck_office_cumulative_amount
        CHECK (cumulative_amount >= 0),

    CONSTRAINT ck_office_incremental_amount
        CHECK (incremental_amount >= 0)
);


-- Indexes
CREATE INDEX idx_ministry_budget_fiscal_year
    ON ministry_budgets(fiscal_year_id);

CREATE INDEX idx_ministry_category_budget
    ON ministry_budget_categories(ministry_budget_id);

CREATE INDEX idx_category_sources_category
    ON category_budget_sources(category_id);

CREATE INDEX idx_office_allocations_organization
    ON office_budget_allocations(organization_id);

CREATE INDEX idx_projects_office_allocation
    ON projects(office_budget_allocation_id);

CREATE INDEX idx_project_history_date
    ON project_expenditure_history(report_date);

CREATE INDEX idx_office_history_date
    ON office_expenditure_history(report_date);
