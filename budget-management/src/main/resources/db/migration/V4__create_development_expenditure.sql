CREATE TABLE development_expenditures (

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    budget_allocation_id BIGINT NOT NULL,

    expenditure_date DATE NOT NULL,

    amount NUMERIC(18,2) NOT NULL,

    description TEXT,

    attachment_path VARCHAR(500),

    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',

    submitted_at TIMESTAMPTZ,

    approved_at TIMESTAMPTZ,

    remarks TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_development_expenditure_allocation
        FOREIGN KEY (budget_allocation_id)
        REFERENCES budget_allocations(id),

    CONSTRAINT chk_development_expenditure_amount
        CHECK (amount > 0),

    CONSTRAINT chk_development_expenditure_status
        CHECK (
            status IN (
                'DRAFT',
                'SUBMITTED',
                'APPROVED',
                'REJECTED'
            )
        )
);

CREATE INDEX idx_development_expenditure_allocation
ON development_expenditures(budget_allocation_id);

CREATE INDEX idx_development_expenditure_date
ON development_expenditures(expenditure_date);

CREATE INDEX idx_development_expenditure_status
ON development_expenditures(status);

