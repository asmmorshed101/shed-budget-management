CREATE TABLE category_expenditure_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES ministry_budget_categories(id),
    expense_head_id BIGINT NOT NULL REFERENCES expense_heads(id),
    report_date DATE NOT NULL,
    cumulative_amount NUMERIC(20,2) NOT NULL,
    incremental_amount NUMERIC(20,2) NOT NULL DEFAULT 0,
    remarks TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_category_expenditure_cumulative CHECK (cumulative_amount >= 0),
    CONSTRAINT ck_category_expenditure_incremental CHECK (incremental_amount >= 0)
);

CREATE INDEX idx_category_expenditure_history
    ON category_expenditure_history(category_id, report_date DESC, id DESC);
