
-- =========================================================
-- V3: Operational Expenditure Module
-- Voucher-free expenditure management
-- With approval workflow and optional file attachment
-- =========================================================


-- =========================================================
-- 1. EXPENSE HEADS
-- Stores operational expenditure categories
-- Examples: Salary, Electricity, Travel, Office Supplies
-- =========================================================

CREATE TABLE expense_heads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    name_bn VARCHAR(150),

    is_active BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- =========================================================
-- 2. OPERATIONAL BUDGET HEADS
-- Stores budget amount against each expense head
-- under a particular budget allocation
-- =========================================================

CREATE TABLE operational_budget_heads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    budget_allocation_id BIGINT NOT NULL,
    expense_head_id BIGINT NOT NULL,

    budgeted_amount NUMERIC(18,2) NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',

    submitted_at TIMESTAMPTZ,
    approved_at TIMESTAMPTZ,

    remarks TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_operational_budget_allocation
        FOREIGN KEY (budget_allocation_id)
        REFERENCES budget_allocations(id),

    CONSTRAINT fk_operational_budget_expense_head
        FOREIGN KEY (expense_head_id)
        REFERENCES expense_heads(id),

    CONSTRAINT uq_operational_budget_expense_head
        UNIQUE (budget_allocation_id, expense_head_id),

    CONSTRAINT ck_operational_budget_amount
        CHECK (budgeted_amount > 0),

    CONSTRAINT ck_operational_budget_status
        CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED'))
);


-- =========================================================
-- 3. OPERATIONAL EXPENDITURES
-- Stores individual expenditure entries
-- No voucher system
-- One record = one expenditure amount
-- Attachment is optional
-- =========================================================

CREATE TABLE operational_expenditures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    operational_budget_head_id BIGINT NOT NULL,

    expenditure_date DATE NOT NULL,
    amount NUMERIC(18,2) NOT NULL,

    description TEXT,

    -- Optional supporting document path
    attachment_path VARCHAR(500),

    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',

    submitted_at TIMESTAMPTZ,
    approved_at TIMESTAMPTZ,

    remarks TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_operational_expenditure_budget_head
        FOREIGN KEY (operational_budget_head_id)
        REFERENCES operational_budget_heads(id),

    CONSTRAINT ck_operational_expenditure_amount
        CHECK (amount > 0),

    CONSTRAINT ck_operational_expenditure_status
        CHECK (status IN ('DRAFT', 'SUBMITTED', 'APPROVED', 'REJECTED'))
);


-- =========================================================
-- 4. INDEXES
-- Improves query performance
-- =========================================================

CREATE INDEX idx_operational_budget_allocation
    ON operational_budget_heads(budget_allocation_id);

CREATE INDEX idx_operational_budget_expense_head
    ON operational_budget_heads(expense_head_id);

CREATE INDEX idx_operational_budget_status
    ON operational_budget_heads(status);

CREATE INDEX idx_operational_expenditure_budget_head
    ON operational_expenditures(operational_budget_head_id);

CREATE INDEX idx_operational_expenditure_date
    ON operational_expenditures(expenditure_date);

CREATE INDEX idx_operational_expenditure_status
    ON operational_expenditures(status);


